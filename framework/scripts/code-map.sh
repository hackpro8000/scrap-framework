#!/usr/bin/env bash
# Rebuilds the code map agents read instead of exploring: two files in
# <out dir>, made from the code as it is now, never edited by hand.
#
#   code-map.sh [<repo root> [<out dir>]]
#
# Both arguments are optional; <repo root> defaults to the git top level of
# the current directory, and <out dir> defaults to <repo root>/.codemap.
#
#   overview.md   each folder under src/ and its modules: small enough to
#                 load every session
#   modules.txt   one line per module, for rg:
#                 path | purpose | public functions | requires
#
# The purpose is the first sentence of the module's header comment; the
# functions and requires come from the code itself (`function Name.fn(`,
# `require(...)`), so they cannot drift from it.
set -euo pipefail

root="${1:-$(git rev-parse --show-toplevel)}"
out="${2:-${root}/.codemap}"
mkdir -p "${out}"
out="$(cd "${out}" && pwd)"
cd "${root}"

find src -name '*.luau' | LC_ALL=C sort | while read -r file; do
	awk -v path="${file}" '
		# The header: the block comment near the top. Its first line is the
		# module name, the paragraph after it the purpose.
		!started && /^--\[\[/ && NR <= 4 { started = 1; next }
		started && !ended && /^\]\]/ { ended = 1 }
		started && !ended {
			line = $0
			sub(/^[ \t]+/, "", line)
			if (name == "") { if (line != "") name = line; next }
			if (!done_purpose) {
				if (line == "") { if (purpose != "") done_purpose = 1; next }
				purpose = purpose (purpose == "" ? "" : " ") line
			}
			next
		}
		match($0, /^function [A-Za-z_][A-Za-z0-9_]*[.:][A-Za-z_][A-Za-z0-9_]*\(/) {
			fn = substr($0, 10, RLENGTH - 10)
			sub(/^[A-Za-z_][A-Za-z0-9_]*[.:]/, "", fn)
			fns = fns (fns == "" ? "" : " ") fn
		}
		{
			rest = $0
			while (match(rest, /require\([^)]*\)/)) {
				req = substr(rest, RSTART + 8, RLENGTH - 9)
				rest = substr(rest, RSTART + RLENGTH)
				n = split(req, parts, /[.\/]/)
				dep = parts[n]
				gsub(/["@]/, "", dep)
				if (dep != "" && !(dep in seen)) { seen[dep] = 1; deps = deps (deps == "" ? "" : " ") dep }
			}
		}
		END {
			# First sentence: up to the first ". ".
			s = purpose
			if (match(s, /\. /)) s = substr(s, 1, RSTART)
			if (length(s) > 180) s = substr(s, 1, 177) "..."
			printf "%s | %s | %s | %s\n", path, s, fns, deps
		}
	' "${file}"
done > "${out}/modules.txt"

{
	echo "# Code map (generated by code-map.sh; do not edit)"
	echo
	echo "Folders under src/ and their modules. For one module's purpose,"
	echo "public functions and requires: rg -i '<word>' .codemap/modules.txt"
	echo
	awk -F ' \\| ' '
		{
			n = split($1, p, "/")
			dir = p[1]; for (i = 2; i < n; i++) dir = dir "/" p[i]
			mod = p[n]; sub(/\.luau$/, "", mod)
			if (!(dir in mods)) order[++count] = dir
			mods[dir] = mods[dir] (mods[dir] == "" ? "" : ", ") mod
		}
		END { for (i = 1; i <= count; i++) printf "- %s: %s\n", order[i], mods[order[i]] }
	' "${out}/modules.txt"
} > "${out}/overview.md"
